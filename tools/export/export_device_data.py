"""
LiveEarth Device Data Packager & Exporter
将经过严格 QA 审查的生产数据导出为轻量化的嵌入式 C 头文件或二进制/紧凑 JSON，用于离线存储。
"""

import os
import json

DATA_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), "../../data"))
OUTPUT_HEADER = os.path.abspath(os.path.join(os.path.dirname(__file__), "../../src/generated_data.h"))

def export_for_firmware():
    with open(os.path.join(DATA_DIR, "places.json"), "r", encoding="utf-8") as f:
        places = json.load(f)

    with open(os.path.join(DATA_DIR, "categories.json"), "r", encoding="utf-8") as f:
        categories = json.load(f)

    compact_places = []
    for p in places:
        compact_places.append({
            "id": p["id"],
            "name": p["name"],
            "local_name": p.get("local_name", ""),
            "country": p["country"],
            "region": p.get("region", ""),
            "lat": p["latitude"],
            "lon": p["longitude"],
            "cat": p["category"],
            "desc": p["description"][:160],  # 截断适配小屏
            "cams": p.get("cameras", [])
        })

    json_str = json.dumps(compact_places, separators=(',', ':'), ensure_ascii=False)
    # 转义 C 语言字符串
    c_escaped_str = json_str.replace('\\', '\\\\').replace('"', '\\"')

    header_content = f"""#pragma once
// Auto-generated by tools/export/export_device_data.py - DO NOT EDIT MANUALLY
// Total offline places: {len(compact_places)}

#include <stddef.h>

static const size_t OFFLINE_PLACES_COUNT = {len(compact_places)};
static const char OFFLINE_PLACES_JSON[] PROGMEM = "{c_escaped_str}";
"""
    os.makedirs(os.path.dirname(OUTPUT_HEADER), exist_ok=True)
    with open(OUTPUT_HEADER, "w", encoding="utf-8") as f:
        f.write(header_content)

    print(f"[Export] Generated {OUTPUT_HEADER} ({len(compact_places)} places, payload size: {len(json_str)} bytes)")

if __name__ == "__main__":
    export_for_firmware()
